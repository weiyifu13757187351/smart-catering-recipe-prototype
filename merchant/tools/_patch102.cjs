const fs = require('fs');
const path = require('path');
const D = path.join(__dirname, '..');
const log = [];
const ed = (file, pairs) => {
  const P = path.join(D, file);
  let t = fs.readFileSync(P, 'utf8');
  pairs.forEach(([from, to, tag]) => {
    if (!t.includes(from)) throw new Error('未命中：' + tag);
    t = t.replace(from, to);
    log.push(tag);
  });
  fs.writeFileSync(P, t, 'utf8');
};

